#!/usr/bin/env node

/**
 * Shopify App TOML Generator
 * Generates shopify.app.<env>.toml from current environment configuration.
 *
 * Usage:
 *   node scripts/generate-toml.mjs [targetEnv] [outputPath]
 * Examples:
 *   node scripts/generate-toml.mjs development
 *   node scripts/generate-toml.mjs production shopify.app.prod.toml
 */

import fs from "fs";
import path from "path";

const targetEnv = process.argv[2] || process.env.NODE_ENV || "development";
const outputPath = process.argv[3] || `shopify.app.${targetEnv}.toml`;

const clientId = process.env.SHOPIFY_API_KEY || "<your-shopify-api-key>";
const appName = process.env.APP_NAME || "Shopify App Starter Pro";
const appHandle = process.env.APP_HANDLE || "shopify-app-starter-pro";
const appUrl = process.env.SHOPIFY_APP_URL || "https://<your-app-tunnel-domain>.example.com";
const scopes = process.env.SHOPIFY_SCOPES || "read_products,write_products,read_orders";
const proxyPrefix = process.env.APP_PROXY_PREFIX || "apps";
const proxySubpath = process.env.APP_PROXY_SUBPATH || "starter-proxy";

const tomlContent = `# ==============================================================================
# Shopify CLI Application Configuration (${targetEnv})
# Auto-generated by scripts/generate-toml.mjs
# ==============================================================================

client_id = "${clientId}"
name = "${appName}"
handle = "${appHandle}"
application_url = "${appUrl}"
embedded = true

[build]
automatically_update_urls_on_dev = true
dev_store_url = ""

[access_scopes]
scopes = "${scopes}"

[auth]
redirect_urls = [
  "${appUrl}/api/auth/callback"
]

[webhooks]
api_version = "2025-01"

[webhooks.privacy_compliance]
customer_data_request_url = "${appUrl}/api/webhooks"
customer_deletion_url = "${appUrl}/api/webhooks"
shop_deletion_url = "${appUrl}/api/webhooks"

[app_proxy]
url = "${appUrl}/api/proxy/sample"
subpath = "${proxySubpath}"
prefix = "${proxyPrefix}"
`;

const resolvedPath = path.resolve(process.cwd(), outputPath);
fs.writeFileSync(resolvedPath, tomlContent, "utf-8");
console.log(`[Shopify Config] Successfully generated TOML configuration for '${targetEnv}' at: ${outputPath}`);
